// Task 1: variables and template literal

// const for values that never change
const studentName = "Maaz Panawala";
const rollNumber = "26K-2510";
const section = "BDS-1A";

// let for a value that changes later
let semester = 1;
semester = 2; // updated from 1 to 2

// Template literal (backticks)
console.log(`Hello, my name is ${studentName}, roll number ${rollNumber}, from section ${section}, currently in semester ${semester}.`);
